"""Single entry point. ``python -m qheart.cli <command>``.

One entry point, one config format, one results ledger. The reason is reproducibility
in the narrow sense that matters at judging time: every number in the report can be
regenerated by a command that is written down, and nobody has to remember which
notebook cell was run in which order. Notebooks are for looking at things; anything
that produces a reported number goes through here.

Commands
    schema      print the data contract
    models      print the model registry
    params      print circuit parameter counts and matched Control-C sizing
    budget      print the O(N^2) quantum-kernel cost estimate
    data        load, validate and cache the processed dataset
    audit       write data_audit.json/.md -- run this before modelling
    baselines   score all classical baselines
    kernel      precompute the Gram matrix, then score the quantum kernel SVC
    vqc         train and score the variational classifier
    control     score Control-C, sized from the circuit at runtime
    compare     aggregate the ledger, run McNemar + Holm, render tables and figures
"""

