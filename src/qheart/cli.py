def cmd_budget(a) -> int:
    from qheart.quantum.budget import estimate_kernel_cost

    n_test = a.n_samples // a.folds
    n_train = a.n_samples - n_test

    print(
        estimate_kernel_cost(
            n_train,
            n_test,
            seconds_per_eval=a.seconds_per_eval,
            folds=a.folds * a.repeats,
        ).report()
    )

    return 0


def cmd_data(a) -> int:
    from qheart import schema as S

    df = _load_frame(a)

    PROCESSED.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    if PROCESSED.exists() and not a.force:
        print(
            f"{PROCESSED} exists; pass --force to overwrite"
        )

    else:
        try:
            df.to_parquet(PROCESSED)
            print(f"wrote {PROCESSED}")

        except Exception as e:
            # pyarrow is optional; CSV is a valid fallback.
            alt = PROCESSED.with_suffix(".csv")

            df.to_csv(
                alt,
                index=False,
            )

            print(
                f"parquet unavailable ({type(e).__name__}); "
                f"wrote {alt} instead"
            )

    print(
        f"{len(df)} rows x {df.shape[1]} columns, "
        f"prevalence {df[S.TARGET].mean():.3f}"
    )

    print(f"target: {S.TARGET}")

    print(
        "target counts: "
        f"{df[S.TARGET].value_counts().sort_index().to_dict()}"
    )

    print(
        f"missing values: {int(df.isna().sum().sum())}"
    )

    return 0


