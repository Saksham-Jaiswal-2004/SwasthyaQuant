# ------------------------------------------------------------------ helpers
def _load_config(path: str | None) -> dict:
    if not path:
        return {}

    import yaml

    with open(path) as fh:
        return yaml.safe_load(fh) or {}


# YAML path -> argparse destination.
CONFIG_MAP = {
    "seed": "seed",
    "data.source": "source",
    "data.raw_path": "raw",
    "split.n_splits": "folds",
    "split.n_repeats": "repeats",
    "features.set": "feature_set",
    "quantum.n_qubits": "n_qubits",
    "quantum.depth": "depth",
    "quantum.shots": "shots",
    "quantum.entangler": "entangler",
    "kernel.reps": "reps",
    "kernel.entanglement": "entanglement",
    "kernel.C": "C",
    "kernel.max_samples": "max_samples",
    "training.epochs": "epochs",
    "training.lr": "lr",
    "training.batch_size": "batch_size",
    "training.gradient_method": "gradient_method",
    "report.ledger": "ledger",
}


def _dig(cfg: dict, dotted: str):
    cur = cfg

    for part in dotted.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return None, False

        cur = cur[part]

    return cur, True


def _subparser_for(parser, cmd: str):
    """Return the command subparser."""

    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action.choices.get(cmd)

    return None


def _apply_config(args, parser) -> list[str]:
    """Overlay YAML values onto arguments left at parser defaults.

    Precedence:
        command line > config file > parser default
    """

    cfg = _load_config(getattr(args, "config", None))
    sp = _subparser_for(parser, getattr(args, "cmd", None))

    if not cfg or sp is None:
        return []

    sentinel = object()
    defaults = {a.dest: a.default for a in sp._actions}

    applied = []

    for dotted, dest in CONFIG_MAP.items():
        if dest not in defaults or not hasattr(args, dest):
            continue

        # Explicit command-line values always win.
        if getattr(args, dest) != defaults.get(dest, sentinel):
            continue

        val, found = _dig(cfg, dotted)

        if found and val != defaults[dest]:
            setattr(args, dest, val)
            applied.append(f"{dotted}={val!r}")

    return applied


# ------------------------------------------------------------------ dataset
def _load_frame(a):
    """Load and validate the raw 70k cardiovascular dataset."""

    from qheart import schema as S
    from qheart.data import load

    raw = Path(getattr(a, "raw", "data/raw/cardio_train.csv"))

    if not raw.exists():
        print(
            f"missing {raw}\n"
            f"  run: bash scripts/fetch_data.sh\n"
            f"  expected the 70,000-row cardiovascular dataset at this path",
            file=sys.stderr,
        )
        raise SystemExit(2)

    df = load(
        getattr(a, "source", "cardio_70000"),
        raw,
    )

    S.validate(df)

    return df

    
def _design_matrix(a):
    raw = _load_frame(a)

    from qheart import schema as S
    from qheart.features.clinical import add_clinical_features
    from qheart.features.select import CANDIDATE_FEATURES

    # Keep the raw 70k cardiovascular feature space here.
    # ClinicalRepresentation performs the deterministic clinical
    # feature engineering inside each CV training fold.
    Xdf = raw.loc[:, S.FEATURES].copy()

    y = raw[S.TARGET].to_numpy(dtype=int)

    # Derived frame is retained for audit/reporting/display only.
    clinical = add_clinical_features(raw)

    return Xdf, y, clinical, list(CANDIDATE_FEATURES)


def _n_qubits_dense(n_features: int) -> int:
    try:
        from qheart.quantum.encodings import n_qubits_for

        return n_qubits_for(
            n_features,
            "dense_angle",
        )

    except Exception:
        return (n_features + 1) // 2


# ------------------------------------------------------------------ scoring
def _score(
    a,
    name,
    factory,
    X,
    y,
    *,
    n_params=None,
    extra=None,
    label=None,
    groups=None,
):
    """Run one model through the shared harness and append it to the ledger.

    Every reported number goes through this function. One CV loop, one threshold
    rule, one ledger: if a model is scored some other way its numbers are not
    comparable, and a table of numbers that are not comparable is worse than
    no table.
    """
    from qheart.eval.harness import append_to_ledger, evaluate

    res = evaluate(
        factory,
        X,
        y,
        model_name=label or name,
        groups=groups,
        n_splits=a.folds,
        n_repeats=a.repeats,
        seed=a.seed,
        n_trainable_params=n_params,
        config={
            "source": a.source,
            "feature_set": a.feature_set,
            "seed": a.seed,
            "folds": a.folds,
            "repeats": a.repeats,
            **(extra or {}),
        },
    )
    append_to_ledger(res, a.ledger)
    return res


