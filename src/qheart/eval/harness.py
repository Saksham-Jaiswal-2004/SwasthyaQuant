"""The cross-validation harness.

Every model in the project is scored through here.

One loop, one set of folds, one metric implementation, for classical
baselines, quantum kernels, VQCs and Control-C alike. That is what makes
the comparison apples-to-apples.

The harness deliberately preserves pandas DataFrames when supplied.
This is required because fold-safe preprocessing pipelines need the
original feature names and must fit all learned transformations using
training-fold data only.

Two details are easy to get wrong and are handled here:

* The decision threshold is chosen on the training folds, never on test.
  Tuning a threshold on the test set is a quiet form of overfitting.

* Out-of-fold predictions are retained so that McNemar's test can compare
  two models on identical rows afterwards, without refitting anything.

When ``groups`` are supplied, duplicate/group-aware repeated stratified
folds are used. This prevents identical feature vectors from appearing in
both training and test data.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Protocol

import numpy as np
import pandas as pd

from qheart.data.splits import (
    repeated_stratified_folds,
    repeated_group_stratified_folds,
)
from qheart.eval.metrics import (
    aggregate,
    best_threshold_youden,
    summary,
)

__all__ = [
    "Model",
    "RunResult",
    "evaluate",
    "append_to_ledger",
]


class Model(Protocol):
    """Interface required by the evaluation harness.

    Models may internally contain preprocessing pipelines. In particular,
    scikit-learn Pipelines can receive the raw clinical DataFrame and fit
    their preprocessing steps using only the training fold.
    """

    def fit(
        self,
        X,
        y: np.ndarray,
    ) -> "Model":
        ...

    def predict_proba(
        self,
        X,
    ) -> np.ndarray:
        ...


def _positive_proba(
    model: Model,
    X,
) -> np.ndarray:
    """Return positive-class probabilities as a 1-D array."""

    p = np.asarray(
        model.predict_proba(X),
        dtype=float,
    )

    if p.ndim == 2:
        if p.shape[1] != 2:
            raise ValueError(
                "expected 2 columns of probabilities, "
                f"got {p.shape}"
            )

        return p[:, 1]

    return p.ravel()


@dataclass
class RunResult:
    """All results generated by one model evaluation."""

    model_name: str

    per_fold: list[dict[str, float]] = field(
        default_factory=list
    )

    agg: dict[str, dict[str, float]] = field(
        default_factory=dict
    )

    oof_proba: np.ndarray | None = None

    oof_pred: np.ndarray | None = None

    thresholds: list[float] = field(
        default_factory=list
    )

    fit_seconds: list[float] = field(
        default_factory=list
    )

    n_trainable_params: int | None = None

    config: dict[str, Any] = field(
        default_factory=dict
    )

    def headline(self) -> str:
        se = self.agg.get(
            "sensitivity",
            {},
        )

        sp = self.agg.get(
            "specificity",
            {},
        )

        suffix = (
            f", {self.n_trainable_params} params]"
            if self.n_trainable_params
            else "]"
        )

        return (
            f"{self.model_name}: "
            f"sensitivity {se.get('mean', float('nan')):.3f}"
            f" +/- {se.get('sd', float('nan')):.3f}, "
            f"specificity {sp.get('mean', float('nan')):.3f}"
            f" +/- {sp.get('sd', float('nan')):.3f}"
            f"  [{len(self.per_fold)} folds"
            f"{suffix}"
        )


def _take_rows(
    X,
    indices: np.ndarray,
):
    """Select rows without destroying DataFrame structure.

    pandas DataFrames must use .iloc so that feature names survive into
    fold-safe preprocessing. NumPy arrays continue to use ordinary
    positional indexing.
    """

    if isinstance(X, pd.DataFrame):
        return X.iloc[indices].copy()

    return X[indices]


def _validate_inputs(
    X,
    y: np.ndarray,
) -> tuple[Any, np.ndarray]:
    """Validate evaluation inputs without fitting anything."""

    if isinstance(X, pd.DataFrame):
        if X.ndim != 2:
            raise ValueError(
                "X must be a 2-dimensional DataFrame."
            )

        if not X.index.is_unique:
            raise ValueError(
                "X must have a unique index."
            )

        X_out = X.copy()

    else:
        X_out = np.asarray(X)

        if X_out.ndim != 2:
            raise ValueError(
                "X must be a 2-dimensional array."
            )

    y_out = np.asarray(
        y
    ).ravel()

    if len(X_out) != len(y_out):
        raise ValueError(
            "X and y must contain the same number of rows: "
            f"{len(X_out)} != {len(y_out)}."
        )

    if y_out.size == 0:
        raise ValueError(
            "Cannot evaluate an empty dataset."
        )

    if not np.isfinite(
        y_out.astype(float)
    ).all():
        raise ValueError(
            "y contains non-finite values."
        )

    return X_out, y_out


def evaluate(
    build_model: Callable[[], Model],
    X,
    y: np.ndarray,
    *,
    model_name: str,
    groups: np.ndarray | None = None,
    n_splits: int = 5,
    n_repeats: int = 5,
    seed: int = 20260830,
    tune_threshold: bool = True,
    fixed_threshold: float = 0.5,
    n_trainable_params: int | None = None,
    config: dict[str, Any] | None = None,
    verbose: bool = True,
) -> RunResult:
    """Fit and score ``build_model()`` over repeated stratified folds.

    When ``groups`` is supplied, repeated group-stratified folds are used
    so that identical feature vectors cannot cross train/test boundaries.

    Parameters
    ----------
    build_model:
        Factory returning a fresh model for every fold.

    X:
        Either a pandas DataFrame or NumPy array.

        A DataFrame is intentionally preserved. This allows a model such
        as a scikit-learn Pipeline to perform clinical feature engineering,
        feature selection, imputation and scaling using training-fold data
        only.

    y:
        Binary target.

    groups:
        Optional group identifier for every row.

        When supplied, all rows with the same group ID remain in the same
        train/test fold. This is used for duplicate-aware evaluation of
        the 70k cardiovascular dataset.

    Notes
    -----
    No preprocessing is fitted in this function.

    The model factory is responsible for providing any preprocessing
    required by the model. This keeps the harness model-agnostic while
    ensuring that every fold receives an independent model instance.
    """

    X, y = _validate_inputs(
        X,
        y,
    )

    # ---------------------------------------------------------------
    # Validate optional group IDs.
    # ---------------------------------------------------------------

    if groups is not None:
        groups = np.asarray(groups)

        if groups.ndim != 1:
            groups = groups.ravel()

        if groups.size != y.size:
            raise ValueError(
                "groups must contain exactly one group ID per row: "
                f"{groups.size} != {y.size}"
            )

    res = RunResult(
        model_name=model_name,
        n_trainable_params=n_trainable_params,
        config=config or {},
    )

    # One OOF vector is retained. As in the original implementation,
    # later repeats overwrite earlier repeats. Within each repeat,
    # every observation appears exactly once as test data.
    oof_p = np.full(
        y.size,
        np.nan,
        dtype=float,
    )

    oof_hat = np.full(
        y.size,
        -1,
        dtype=int,
    )

    # ---------------------------------------------------------------
    # Select the fold generator.
    #
    # No groups:
    #     ordinary repeated stratification
    #
    # Groups:
    #     duplicate/group-aware repeated stratification
    # ---------------------------------------------------------------

    if groups is None:
        folds = repeated_stratified_folds(
            y,
            n_splits,
            n_repeats,
            seed,
        )
    else:
        folds = repeated_group_stratified_folds(
            y,
            groups,
            n_splits,
            n_repeats,
            seed,
        )

    for train, test, meta in folds:
        # ---------------------------------------------------------------
        # Preserve DataFrame feature names.
        #
        # This is the critical leakage-safety change:
        #
        #     X_train -> model.fit()
        #     X_test  -> model.predict_proba()
        #
        # A model Pipeline can therefore fit its selector/imputer/scaler
        # on X_train only.
        # ---------------------------------------------------------------

        X_train = _take_rows(
            X,
            train,
        )

        X_test = _take_rows(
            X,
            test,
        )

        y_train = y[train]
        y_test = y[test]

        # Fresh model every fold.
        model = build_model()

        t0 = time.perf_counter()

        model.fit(
            X_train,
            y_train,
        )

        fit_seconds = (
            time.perf_counter()
            - t0
        )

        res.fit_seconds.append(
            fit_seconds
        )

        # ---------------------------------------------------------------
        # Threshold selection uses TRAINING data only.
        # ---------------------------------------------------------------

        if tune_threshold:
            p_train = _positive_proba(
                model,
                X_train,
            )

            thr = best_threshold_youden(
                y_train,
                p_train,
            )

        else:
            thr = fixed_threshold

        thr = float(thr)

        res.thresholds.append(
            thr
        )

        # ---------------------------------------------------------------
        # Test predictions.
        #
        # X_test is transformed by the model's already-fitted pipeline.
        # No fitting occurs here.
        # ---------------------------------------------------------------

        p_test = _positive_proba(
            model,
            X_test,
        )

        if not np.isfinite(
            p_test
        ).all():
            raise ValueError(
                f"{model_name} produced non-finite "
                "test probabilities."
            )

        m = summary(
            y_test,
            p_test,
            thr,
        )

        m.update(
            rep=meta.rep,
            fold=meta.fold,
            n_train=meta.n_train,
            fit_seconds=fit_seconds,
        )

        res.per_fold.append(
            m
        )

        # ---------------------------------------------------------------
        # OOF predictions.
        # ---------------------------------------------------------------

        oof_p[test] = p_test

        oof_hat[test] = (
            p_test >= thr
        ).astype(int)

        if verbose:
            print(
                f"  {model_name} "
                f"rep{meta.rep} "
                f"fold{meta.fold}: "
                f"sens={m['sensitivity']:.3f} "
                f"spec={m['specificity']:.3f} "
                f"pr_auc={m['pr_auc']:.3f} "
                f"thr={thr:.3f}"
            )

    # ---------------------------------------------------------------
    # Aggregate fold-level results.
    # ---------------------------------------------------------------

    res.agg = aggregate(
        res.per_fold
    )

    res.oof_proba = oof_p
    res.oof_pred = oof_hat

    if verbose:
        print(
            res.headline()
        )

    return res


def append_to_ledger(
    res: RunResult,
    path: str | Path = "results/runs/ledger.csv",
    extra: dict[str, Any] | None = None,
) -> Path:
    """Append one row per fold to the append-only results ledger.

    The ledger is the audit trail. Every number in the final report must
    be traceable to rows here.
    """

    p = Path(path)

    p.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    rows = []

    for m in res.per_fold:
        row = {
            "model": res.model_name,
            "n_trainable_params": (
                res.n_trainable_params
            ),
            "config_json": json.dumps(
                res.config,
                sort_keys=True,
                default=str,
            ),
            **m,
            **(extra or {}),
        }

        rows.append(row)

    df = pd.DataFrame(
        rows
    )

    df.to_csv(
        p,
        mode="a",
        header=not p.exists(),
        index=False,
    )

    return p