def main(argv: list[str] | None = None) -> int:
    parser = build_parser()

    a = parser.parse_args(argv)

    applied = _apply_config(
        a,
        parser,
    )

    if applied:
        print(
            f"config {a.config}: "
            + ", ".join(applied)
        )

    return int(
        a.fn(a) or 0
    )


